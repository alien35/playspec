import { existsSync, renameSync } from 'node:fs';
import { resolve } from 'node:path';
import { loadConfig } from '../config.ts';
import { readFileSafe, writeFileSafe, readJsonSafe, ensureDir } from '../utils/fsUtils.ts';
import { c, printBanner, badge } from '../utils/formatting.ts';
import { extractDiagramFromMarkdown } from '../generator/diagramInjector.ts';

export function runArchive(slug: string): void {
  const config = loadConfig();
  const changeDir = resolve(config.changesDir, slug);
  if (!existsSync(changeDir)) {
    console.error(c('red', `❌ Error: Change directory not found: ${changeDir}`));
    process.exit(1);
  }

  const metaPath = resolve(changeDir, 'meta.json');
  const meta = readJsonSafe<any>(metaPath, { slug, title: slug, status: 'verified' });

  printBanner(`Archive Feature: ${meta.title || slug}`, 'Promoting to living specs and archiving change');

  // 1. Promote to Living Specs (specs/features/<slug>.md)
  ensureDir(config.livingSpecsDir);
  const specContent = readFileSafe(resolve(changeDir, 'spec.md'), '');
  const proposalContent = readFileSafe(resolve(changeDir, 'proposal.md'), '');
  const designPath = resolve(changeDir, 'design.md');

  const sequenceDiagram = extractDiagramFromMarkdown(designPath);

  const livingSpecPath = resolve(config.livingSpecsDir, `${slug}.md`);
  const relativeTestPath = `${config.e2e.dir.replace(process.cwd() + '/', '')}/tests/${slug}.e2e.ts`;
  const relativePagePath = `${config.e2e.dir.replace(process.cwd() + '/', '')}/pages/${slug}.page.ts`;
  const relativeFixturePath = `${config.e2e.dir.replace(process.cwd() + '/', '')}/fixtures/${slug}.ts`;

  const diagramBlock = sequenceDiagram
    ? `\n## Reality-Verified Sequence Diagram\n_Generated from passing test execution: [\`${relativeTestPath}\`](../../${relativeTestPath})_\n\n${sequenceDiagram}\n\n---\n`
    : '';

  const livingSpecBody = `<!-- Generated by PlaySpec on ${new Date().toISOString()} -->
# Living Specification: ${meta.title || slug}

- **Executable E2E Test**: [\`${relativeTestPath}\`](../../${relativeTestPath})
- **Page Object**: [\`${relativePagePath}\`](../../${relativePagePath})
- **Fixture**: [\`${relativeFixturePath}\`](../../${relativeFixturePath})
- **Run Command**: \`npm run test:e2e:${slug}\` (or fast mode: \`npm run test:e2e:${slug}:fast\`)

---
${diagramBlock}
${specContent}

---

## Background & Scope
${proposalContent}
`;

  writeFileSafe(livingSpecPath, livingSpecBody);
  console.log(`  ${badge('green', 'promoted')} Living spec saved to ${c('bold', `specs/features/${slug}.md`)}`);

  // 2. Update E2E README if available
  if (config.e2e.readmePath && existsSync(config.e2e.readmePath)) {
    const e2eReadme = readFileSafe(config.e2e.readmePath, '');
    if (!e2eReadme.includes(`${slug}.e2e.ts`)) {
      const readmeSection = `
## ${meta.title || slug} E2E Suite

Covered by \`tests/${slug}.e2e.ts\`:

- Primary specification documented in \`specs/features/${slug}.md\`.
- Run standard suite:
  \`\`\`bash
  npm run test:e2e:${slug}
  \`\`\`
- Run fast mode (skips screenshots):
  \`\`\`bash
  npm run test:e2e:${slug}:fast
  \`\`\`
`;
      writeFileSafe(config.e2e.readmePath, e2eReadme.trimEnd() + '\n' + readmeSection);
      console.log(`  ${badge('green', 'updated')} Appended suite docs to ${c('bold', config.e2e.readmePath.replace(process.cwd() + '/', ''))}`);
    }
  }

  // 3. Move change directory to changes/archive/<date>-<slug>
  ensureDir(config.archiveDir);
  const dateStr = new Date().toISOString().slice(0, 10);
  const archiveTarget = resolve(config.archiveDir, `${dateStr}-${slug}`);

  renameSync(changeDir, archiveTarget);
  console.log(`  ${badge('green', 'archived')} Moved ${c('bold', `changes/${slug}`)} to ${c('bold', `changes/archive/${dateStr}-${slug}`)}`);

  console.log(`\n${c('bold', c('brightGreen', '✨ Feature Successfully Archived & Merged into Living Specs!'))}\n`);
}
